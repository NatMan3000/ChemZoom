// The data contract every part of ChemZoom builds against.
// Layers, smallest first: elements -> molecules -> materials -> collections.
// The 3D viewers know nothing about filament: a new topic is new data, not new viewer code.

/** Text at two depths: `simple` reads right for a curious 12-year-old, `deeper` adds the real chemistry. */
export interface Text {
  simple: string
  deeper?: string
}

export interface SourceRef {
  label: string
  url: string
}

/** A claim shown in the app, with where it came from. */
export interface Fact {
  text: Text
  sources: SourceRef[]
}

// ---------------------------------------------------------------- elements

export type ElementSymbol = 'H' | 'C' | 'N' | 'O' | 'F' | 'Na' | 'Si' | 'P' | 'S' | 'Cl'

export interface ElementInfo {
  symbol: ElementSymbol
  name: string
  number: number // protons
  colour: string // Jmol/CPK hex, tuned to read on the dark stage
  radius: number // ball radius in scene units (angstrom-scaled for ball-and-stick)
  bondsUsually: number // how many bonds it normally makes (C 4, N 3, O 2, H 1)
  blurb: Text
}

// ---------------------------------------------------------------- molecules

export interface Atom {
  el: ElementSymbol
  x: number // angstroms, centred on the molecule's centre
  y: number
  z: number
  charge?: number
}

export interface Bond {
  a: number // atom index
  b: number
  order: 1 | 2 | 3
  aromatic?: boolean // part of a benzene-style ring (drawn as order 1 or 2 per the Kekule form, flagged here)
}

/** A named set of atoms to highlight: the repeat unit, a functional group, a weak spot. */
export interface AtomGroup {
  id: string
  label: string
  kind: 'repeat-unit' | 'monomer' | 'functional-group' | 'weak-spot'
  atoms: number[]
  note?: Text
}

/** Generated by scripts/build-molecules.py (RDKit) into src/data/molecules/<id>.json. */
export interface Molecule {
  id: string
  name: string
  formula: string
  smiles: string
  atoms: Atom[]
  bonds: Bond[]
  groups: AtomGroup[]
  sources: SourceRef[]
}

// ---------------------------------------------------------------- materials

export type MaterialId = 'pla' | 'petg' | 'tpu' | 'abs' | 'asa'

/** The zoom, outermost first. Every material walks the same six steps. */
export type ZoomLevel = 'spool' | 'strand' | 'tangle' | 'chain' | 'molecule' | 'atom'
export const ZOOM_LEVELS: ZoomLevel[] = ['spool', 'strand', 'tangle', 'chain', 'molecule', 'atom']

/**
 * What the inside of the strand looks like at the `tangle` level.
 * - semicrystalline: tangled chains with some neatly folded, aligned patches (PLA)
 * - amorphous: a pure random tangle, no ordered patches (PETG)
 * - segmented: chains alternate hard bits that clump into islands and soft springy bits between (TPU)
 * - rubber-toughened: a glassy tangle with soft rubber blobs scattered through it (ABS, ASA)
 */
export type Morphology = 'semicrystalline' | 'amorphous' | 'segmented' | 'rubber-toughened'

/** Compare-bar traits, scored 1 (low) to 5 (high). */
export type TraitId = 'strength' | 'flexibility' | 'heat' | 'uv' | 'easy' | 'moisture'

export interface Trait {
  id: TraitId
  score: 1 | 2 | 3 | 4 | 5
  why: Text
}

export interface Temps {
  tgC: number // glass transition: below it the chains are frozen stiff, above it they can slide
  meltC?: number // crystal melt, only for materials with crystals (PLA; TPU hard segments)
  nozzleC: [number, number]
  bedC: [number, number]
  hdtC?: number // heat deflection temperature, if the source gives one
}

/** Numbers the concept sims use. Rough, for teaching; each one cites a source in `facts` or `sources`. */
export interface SimParams {
  shrink: 1 | 2 | 3 | 4 | 5 // how much it shrinks and warps as it cools
  uvWeakSpot?: { molecule: string; group: string } // molecule id + AtomGroup id of the bond sunlight attacks
  thirst: 1 | 2 | 3 | 4 | 5 // how much water it soaks up from the air
  rubberBlobs?: { molecule: string } // ABS/ASA: the rubber that toughens it
  hardSegments?: { molecule: string } // TPU: the bit that clumps into hard islands
}

export interface Material {
  id: MaterialId
  short: string // 'PLA'
  fullName: string // 'Polylactic acid'
  nickname: string // 'The plant-based one'
  accent: string // hex, the filament colour on the spool and the material's UI accent
  densityGcm3: number // for the spool maths (1 kg -> metres of 1.75 mm strand)
  madeFrom: Text // where the building blocks come from
  keyIdea: Text // the one sentence that explains how it behaves
  monomers: string[] // molecule ids: the building blocks before they join up
  oligomer: string // molecule id: a few repeat units joined, shown at the `molecule` level
  repeatUnitGroup: string // AtomGroup id in the oligomer to highlight as one repeat unit
  morphology: Morphology
  zoom: Record<ZoomLevel, Text> // caption at each zoom step
  traits: Trait[]
  temps: Temps
  print: {
    enclosure: 'no' | 'helps' | 'yes'
    tips: Text[]
    dryC?: number // drying temperature if it needs drying
  }
  sim: SimParams
  facts: Fact[]
  sources: SourceRef[]
}

// ---------------------------------------------------------------- collections

/** A topic shelf on the home page. 3D printing filaments is the first; others slot in later. */
export interface Collection {
  id: string
  title: string
  blurb: Text
  materials: MaterialId[]
}
